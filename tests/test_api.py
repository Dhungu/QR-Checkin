async def test_check_in_success_then_duplicate(client):
    ev = await make_event(client)
    att = await make_attendee(client, ev["id"])
    body = {"ticket_token": att["ticket_token"], "scanned_by": "gate-1"}

    r = await client.post("/api/v1/check-in", headers=STAFF, json=body)
    assert r.status_code == 200
    data = r.json()
    assert data["status"] == "SUCCESS" and data["attendee"]["full_name"] == "Ada Lovelace" and data["timestamp"]

    r = await client.post("/api/v1/check-in", headers=STAFF, json={**body, "scanned_by": "gate-2"})
    assert r.status_code == 409
    dup = r.json()
    assert dup["status"] == "ALREADY_CHECKED_IN" and dup["checked_in_at"] == data["timestamp"]
    assert dup["scanned_by"] == "gate-1"  # first scan is preserved, not overwritten


async def test_invalid_and_forged_tickets(client):
    r = await client.post("/api/v1/check-in", headers=STAFF, json={"ticket_token": "nope", "scanned_by": "g"})
    assert r.status_code == 404 and r.json() == {"status": "INVALID_TICKET"}
    # Well-formed but unsigned token
    forged = "A" * 32 + "." + "B" * 22
    r = await client.post("/api/v1/check-in", headers=STAFF, json={"ticket_token": forged, "scanned_by": "g"})
    assert r.status_code == 404


async def test_outside_event_window(client):
    future = await make_event(client, start_offset=5, end_offset=8, name="Future")
    past = await make_event(client, start_offset=-8, end_offset=-5, name="Past")
    for ev in (future, past):
        att = await make_attendee(client, ev["id"], email=f"{ev['slug']}@example.com")
        r = await client.post("/api/v1/check-in", headers=STAFF, json={"ticket_token": att["ticket_token"], "scanned_by": "g"})
        assert r.status_code == 403 and r.json()["status"] == "OUTSIDE_EVENT_WINDOW"
    stats = (await client.get(f"/api/v1/events/{future['id']}/stats", headers=STAFF)).json()
    assert stats["checked_in"] == 0  # rejected scans never change state


