def test_production_refuses_default_secrets():
    import pytest
    from pydantic import ValidationError

    from app.core.config import Settings

    with pytest.raises(ValidationError):
        Settings(environment="production", qr_hmac_secret="short", admin_api_key="dev-admin-key", staff_api_key="dev-staff-key")
    Settings(environment="production", qr_hmac_secret="x" * 40, admin_api_key="a" * 20, staff_api_key="b" * 20)
