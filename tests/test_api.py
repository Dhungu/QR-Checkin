async def test_auth_required(client):
    assert (await client.post("/api/v1/events", json={})).status_code == 401
    assert (await client.post("/api/v1/check-in", json={"ticket_token": "x", "scanned_by": "s"})).status_code == 401
    r = await client.post("/api/v1/events", headers=STAFF, json={})
    assert r.status_code == 403  # staff key cannot create events


async def test_event_validation(client):
    now = datetime.now(UTC)
    r = await client.post("/api/v1/events", headers=ADMIN,
                          json={"name": "Bad", "start_time": iso(now), "end_time": iso(now - timedelta(hours=1))})
    assert r.status_code == 422
    r = await client.post("/api/v1/events", headers=ADMIN,
                          json={"name": "Naive", "start_time": "2030-01-01T10:00:00", "end_time": "2030-01-01T12:00:00"})
    assert r.status_code == 422  # timezone required


